"""
SQLAlchemy ORM models for the SIEM backend.

Tables:
    - SecurityEvent: Raw ingested log events.
    - Alert: Alerts generated by detection rules.
    - Incident: Correlated groups of alerts.
    - DetectionRule: Configurable detection rules.
"""

from datetime import datetime, timezone

from sqlalchemy import (
    Boolean,
    Column,
    DateTime,
    Float,
    Integer,
    String,
    Text,
)

from database import Base


def _utcnow() -> datetime:
    """Return the current UTC time (timezone-aware)."""
    return datetime.now(timezone.utc)


class SecurityEvent(Base):
    """A single normalised security log event."""

    __tablename__ = "security_events"

    id = Column(Integer, primary_key=True, index=True)
    timestamp = Column(DateTime, nullable=False)
    event_id = Column(Integer, nullable=False, index=True)
    source = Column(String(255), nullable=False)
    account = Column(String(255), nullable=False, index=True)
    source_ip = Column(String(45), nullable=True)
    computer_name = Column(String(255), nullable=False)
    event_type = Column(String(100), nullable=False, index=True)
    severity = Column(String(20), nullable=False, index=True)
    raw_data = Column(Text, nullable=False)
    ingestion_time = Column(DateTime, default=_utcnow)


class Alert(Base):
    """An alert raised by a detection rule."""

    __tablename__ = "alerts"

    id = Column(Integer, primary_key=True, index=True)
    rule_id = Column(String(100), nullable=False, index=True)
    rule_name = Column(String(255), nullable=False)
    severity = Column(String(20), nullable=False, index=True)
    confidence = Column(Float, nullable=False)
    description = Column(Text, nullable=False)
    evidence = Column(Text, nullable=False)  # JSON
    mitre_tactic = Column(String(100), nullable=True)
    mitre_technique_id = Column(String(50), nullable=True)
    mitre_technique_name = Column(String(255), nullable=True)
    status = Column(String(30), nullable=False, default="New", index=True)
    created_at = Column(DateTime, default=_utcnow)
    event_ids = Column(Text, nullable=False)  # JSON array


class Incident(Base):
    """An incident formed by correlating related alerts."""

    __tablename__ = "incidents"

    id = Column(Integer, primary_key=True, index=True)
    title = Column(String(500), nullable=False)
    description = Column(Text, nullable=False)
    severity = Column(String(20), nullable=False, index=True)
    status = Column(String(30), nullable=False, default="Open", index=True)
    alert_ids = Column(Text, nullable=False)  # JSON array
    timeline = Column(Text, nullable=False)  # JSON array
    mitre_techniques = Column(Text, nullable=False)  # JSON array
    investigation_notes = Column(Text, nullable=True)
    created_at = Column(DateTime, default=_utcnow)
    updated_at = Column(DateTime, default=_utcnow, onupdate=_utcnow)


class DetectionRule(Base):
    """A configurable detection rule definition."""

    __tablename__ = "detection_rules"

    id = Column(String(100), primary_key=True)
    name = Column(String(255), nullable=False)
    description = Column(Text, nullable=False)
    severity = Column(String(20), nullable=False)
    enabled = Column(Boolean, default=True)
    config = Column(Text, nullable=False)  # JSON
    mitre_tactic = Column(String(100), nullable=False)
    mitre_technique_id = Column(String(50), nullable=False)
    mitre_technique_name = Column(String(255), nullable=False)
    created_at = Column(DateTime, default=_utcnow)
